import { boot, group, ok, eq, near, click, editDay, setField, saveBtn, monthText, navTo, switchWorker, report, $, $$ } from './helpers.mjs';

const { w, doc, api, errors } = boot();
const S = () => api.state;
api.setMonth(2026,10); // 2026-11
api.render();
group('正式工：底薪 + 加班');
S().data.regular.settings.baseSalary = 8000;
S().data.regular.settings.autoDays = false;
S().data.regular.settings.daysPerMonth = 21.75;
S().data.regular.settings.hoursPerDay = 8;
S().data.regular.settings.cycleStartDay = 1;
api.render();
const hr = 8000 / (21.75 * 8);
const otPay = Math.round((4 * hr * 1.5 + Number.EPSILON) * 100) / 100;
const dlg = editDay(w, doc, '2026-11-18');
eq('日期是工作日', api.dateType('2026-11-18'), 'workday');
setField(doc, 'otHours', 4);
saveBtn(doc).click();
const rec = S().data.regular.records['2026-11-18'];
ok('正式工记录已保存', !!rec, rec);
eq('加班小时', rec.otHours, 4);
eq('单日工资=加班费', Math.round(api.dayWage('2026-11-18', rec, 'regular')*100)/100, otPay);
const st = api.cycleStats(2026, 10, 'regular');
near('时薪', st.hourlyRate, hr, 0.001);
near('加班费合计', st.otPay, otPay, 0.02);
near('底薪', st.base, 8000, 0.01);
near('实发', st.net, 8000 + otPay, 0.02);
eq('日历显示金额', doc.querySelector('.day[data-date="2026-11-18"] .d-wage')?.textContent, '+' + otPay.toLocaleString('zh-CN',{minimumFractionDigits:2,maximumFractionDigits:2}));
navTo(w, doc, 'details');
const amt = doc.querySelector('.settle-card .money-hero .amt')?.textContent;
eq('明细实发', amt, '¥' + (8000+otPay).toLocaleString('zh-CN',{minimumFractionDigits:2,maximumFractionDigits:2}));
const rows = $$(doc,'.settle-card .li-row').map(r=>r.textContent.replace(/\s+/g,' ').trim());
console.log('  明细行:', rows);

group('正式工：事假与缺勤');
const dlg2 = editDay(w, doc, '2026-11-19');
dlg2.querySelector('[data-action="pick-shift"][data-v="事假"]').click();
saveBtn(doc).click();
const st2 = api.cycleStats(2026,10,'regular');
near('事假扣一天底薪', st2.leaveDeduct, 8*hr, 0.02);
near('实发减少', st2.net, 8000 + otPay - 8*hr, 0.05);
const dlg3 = editDay(w, doc, '2026-11-20');
setField(doc, 'regularHours', 6);
saveBtn(doc).click();
const st3 = api.cycleStats(2026,10,'regular');
near('正班缺 2 小时', st3.shortDeduct, 2*hr, 0.02);

group('临时工');
switchWorker(doc,'temp');
api.setMonth(2026,10); api.render();
S().data.temp.settings.rate = 25;
api.render();
const d2 = editDay(w, doc, '2026-11-18');
setField(doc, 'hours', 8);
eq('单价默认带入设置', d2.querySelector('input[data-field="rate"]').value, '25');
saveBtn(doc).click();
const stt = api.cycleStats(2026,10,'temp');
near('工时工资', stt.pay, 200, 0.01);
eq('出勤天数', stt.attendance, 1);
near('实发', stt.net, 200, 0.01);
eq('出勤天数', stt.attendance, 1);
eq('临时工没有社保公积金字段', doc.querySelector('.settle-card')?.innerHTML.includes('社保'), false);
// 加保险 20 和补贴 50
S().data.temp.monthly['2026-11'] = { deductions:[{name:'保险',amount:20}], allowances:[{name:'饭补',amount:50}] };
api.render();
const stt2 = api.cycleStats(2026,10,'temp');
near('扣保险后实发', stt2.net, 230, 0.01);
navTo(w,doc,'details');
ok('明细有保险/扣款', doc.querySelector('.settle-card')?.textContent.includes('保险'));
ok('明细无公积金', !doc.querySelector('.settle-card')?.textContent.includes('公积金'));

group('计件');
switchWorker(doc,'piece');
api.setMonth(2026,10); api.render();
S().data.piece.settings.items = [{name:'上衣',rate:3.5},{name:'裤子',rate:5}];
S().data.piece.settings.unit = '件';
api.render();
const d3 = editDay(w, doc, '2026-11-18');
d3.querySelector('[data-action="add-piece"]').click();
const names = d3.querySelectorAll('input[data-field^="pname"]');
names[0].value='上衣'; names[0].dispatchEvent(new w.Event('input',{bubbles:true}));
setField(doc,'pqty0',20);
eq('选品项自动带单价', d3.querySelector('input[data-field="prate0"]').value, '3.5');
names[1].value='裤子'; names[1].dispatchEvent(new w.Event('input',{bubbles:true}));
setField(doc,'pqty1',10);
saveBtn(doc).click();
const stp = api.cycleStats(2026,10,'piece');
near('计件工资 20×3.5+10×5', stp.pay, 120, 0.01);
eq('件数合计', stp.qty, 30);
navTo(w, doc, 'calendar');
api.render();
eq('日历显示件数', doc.querySelector('.day[data-date="2026-11-18"] .lunar')?.textContent, '30件');

group('工地记工');
switchWorker(doc,'site');
api.setMonth(2026,10); api.render();
S().data.site.settings.dayRate = 260;
S().data.site.settings.otRate = 30;
api.render();
const d4 = editDay(w, doc, '2026-11-18');
setField(doc,'units',1);
setField(doc,'dayRate',260);
setField(doc,'otHours',2);
setField(doc,'otRate',30);
saveBtn(doc).click();
const ss = api.cycleStats(2026,10,'site');
near('点工 1 个工', ss.dayPay, 260, 0.01);
near('加班 2h', ss.otPay, 60, 0.01);
near('应发', ss.gross, 320, 0.01);
// 借支
const d5 = editDay(w, doc, '2026-11-19');
d5.querySelector('[data-action="site-type"][data-v="borrow"]').click();
setField(doc,'amount',100);
saveBtn(doc).click();
const ss2 = api.cycleStats(2026,10,'site');
near('借支', ss2.borrow, 100, 0.01);
near('未结余款', ss2.net, 220, 0.01);
navTo(w,doc,'details');
const txt = doc.querySelector('.settle-card').textContent.replace(/\s+/g,'');
ok('工地明细显示借支', txt.includes('借支'));
ok('工地明细显示未结', txt.includes('未结余款'));
console.log('  工地行:', $$(doc,'.settle-card .li-row').map(r=>r.textContent.replace(/\s+/g,' ').trim()));

const r = report();
console.log('errors:', errors);
process.exit(r.fail?1:0);
