import { boot, group, ok, eq, near, click, typeNums, saveBtn, navTo, switchWorker, report, $, $$ } from './helpers.mjs';

const { w, doc, api, errors } = boot();
const S = () => api.state;
api.setMonth(2026,10);
navTo(w, doc, 'settings');
api.render();

group('设置页：键盘修改正式工参数');
S().data.regular.settings.autoDays = false;
api.render();
const base = doc.querySelector('#main input[data-set="baseSalary"]');
ok('底薪输入框存在', !!base);
base.focus();
ok('自动打开隐私键盘', doc.getElementById('keypad').classList.contains('on'));
eq('键盘标题为月薪', doc.getElementById('kpLabel').textContent.includes('月薪'), true);
typeNums(w, doc, base, '8000');
doc.querySelector('#kpGrid [data-key="done"]').click();
eq('底薪写入 state', S().data.regular.settings.baseSalary, 8000);
await new Promise(r=>setTimeout(r,250));
ok('localStorage 已同步', (w.localStorage.getItem('gongshi_v3') || '').includes('8000'));
const days = doc.querySelector('#main input[data-set="daysPerMonth"]');
typeNums(w, doc, days, '21.75');
doc.querySelector('#kpGrid [data-key="done"]').click();
eq('计薪天数', S().data.regular.settings.daysPerMonth, 21.75);
// 小时工资提示联动
const hint = doc.getElementById('hourlyHint');
ok('小时工资提示更新为 45.98', hint && hint.textContent.includes('45.98'), hint && hint.textContent);

group('设置页：自动计薪天数');
eq('点击前是固定天数', S().data.regular.settings.autoDays, false);
click(doc, '#main [data-action="toggle-set"][data-attr="autoDays"]');
eq('自动天数打开', S().data.regular.settings.autoDays, true);
ok('提示变成按工作日', doc.getElementById('hourlyHint').textContent.includes('自动'), doc.getElementById('hourlyHint').textContent);
ok('提示天数 = 当月工作日', doc.getElementById('hourlyHint').textContent.includes(String(api.cycleRange(2026,10).dates.filter(k=>!api.isOffDay(k)).length)), doc.getElementById('hourlyHint').textContent);
const cycNow = api.cycleRange(2026,10);
const payDays = cycNow.dates.filter(k=>!api.isOffDay(k)).length;
const autoHr = 8000 / (payDays * 8);
ok('自动时薪 = 8000/(工作日×8)', Math.abs(api.cycleStats(2026,10,'regular').hourlyRate - autoHr) < 0.01, {rate: api.cycleStats(2026,10,'regular').hourlyRate, payDays, expect: autoHr});
click(doc, '#main [data-action="toggle-set"][data-attr="autoDays"]');
eq('改回固定天数', S().data.regular.settings.autoDays, false);
ok('提示回到 21.75 天', doc.getElementById('hourlyHint').textContent.includes('21.75'), doc.getElementById('hourlyHint').textContent);

group('设置页：月度扣款增删');
const addDed = doc.querySelector('#main [data-action="add-item"][data-kind="deductions"]');
const before = doc.querySelectorAll('#main [data-item$=":name"]').length;
click(doc, addDed);
const after = doc.querySelectorAll('#main [data-item$=":name"]').length;
eq('新增扣款行', after, before + 1);
const lastIdx = after - 1;
const nameInp = doc.querySelector(`#main input[data-item="deductions:${lastIdx}:name"]`);
nameInp.value = '个人所得税';
nameInp.dispatchEvent(new w.Event('input', { bubbles: true }));
const amtInp = doc.querySelector(`#main input[data-item="deductions:${lastIdx}:amount"]`);
amtInp.focus();
typeNums(w, doc, amtInp, '120');
doc.querySelector('#kpGrid [data-key="done"]').click();
const mon = S().data.regular.monthly['2026-11'];
ok('扣款项写入', mon.deductions.some(d => d.name === '个人所得税' && d.amount === 120), mon.deductions);
click(doc, `#main [data-action="del-item"][data-kind="deductions"][data-idx="${lastIdx}"]`);
ok('删除扣款行', S().data.regular.monthly['2026-11'].deductions.length === before, S().data.regular.monthly['2026-11'].deductions.length);

group('完整流程：记工 → 明细联动 → 工资条');
navTo(w, doc, 'calendar');
api.render();
click(doc, '#main [data-action="edit-day"][data-date="2026-11-18"]');
const dlg = doc.getElementById('editor');
dlg.querySelector('[data-action="quick-ot"][data-v="2"]').click();
saveBtn(doc).click();
const st = api.cycleStats(2026,10,'regular');
const hrNow = api.cycleStats(2026,10,'regular').hourlyRate;
near('实发 = 底薪 + 2h 加班', st.net, 8000 + 2*hrNow*1.5, 0.03);
navTo(w, doc, 'details');
const amt = doc.querySelector('.settle-card .money-hero .amt').textContent;
ok('明细显示实发', amt.includes('8,137') || amt.includes('8137'), amt);
click(doc, '#main [data-action="payslip"]');
const pd = doc.getElementById('payslipDialog');
ok('工资条打开', pd.hasAttribute('open'));
ok('工资条含实发金额', pd.textContent.includes(amt.replace('¥','')), pd.textContent.slice(0,200));
doc.getElementById('payslipDialog').close();

group('切工种：明细卡片差异');
switchWorker(doc, 'temp');
api.render();
navTo(w, doc, 'details');
api.render();
const tDetail = doc.querySelector('.settle-card').textContent.replace(/\s+/g,'');
ok('临时工结算标题', tDetail.includes('临时工'));
ok('临时工明细不含公积金', !tDetail.includes('公积金'));
ok('临时工明细含保险', tDetail.includes('保险'));
switchWorker(doc, 'site');
api.render();
navTo(w, doc, 'details');
api.render();
const sDetail = doc.querySelector('.settle-card').textContent.replace(/\s+/g,'');
ok('工地结算标题', sDetail.includes('工地'));
ok('工地有未结余款', sDetail.includes('未结余款'));
ok('工地有借支行', sDetail.includes('借支'));
switchWorker(doc, 'piece');
api.render();
navTo(w, doc, 'details');
api.render();
const pDetail = doc.querySelector('.settle-card').textContent.replace(/\s+/g,'');
ok('计件结算标题', pDetail.includes('计件'));
ok('计件有件数', pDetail.includes('件'));

group('背景应用');
click(doc, '#bgBtn');
click(doc, '#bgDialog [data-action="set-bg-preset"][data-id="night"]');
eq('深蓝夜预设', api.theme.preset, 'night');
ok('壁纸层使用深蓝渐变', /243b63|36, 59, 99/.test(doc.getElementById('wallpaper').style.background), doc.getElementById('wallpaper').style.background);
doc.getElementById('bgDialog').close();
ok('背景持久化', (w.localStorage.getItem('gongshi_bg') || '').includes('night'));

group('返回键行为');
click(doc, '#aboutBtn');
eq('弹窗打开时返回键关闭弹窗', w.__onBack(), true);
eq('弹窗已关', doc.getElementById('aboutDialog').hasAttribute('open'), false);
navTo(w, doc, 'details');
eq('明细页返回键回日历', w.__onBack(), true);
eq('已回日历', api.view, 'calendar');
eq('日历页返回键返回 false', w.__onBack(), false);
// 键盘
switchWorker(doc, 'regular');
navTo(w, doc, 'settings');
api.render();
doc.querySelector('#main input[data-set="baseSalary"]').focus();
eq('键盘打开', doc.getElementById('keypad').classList.contains('on'), true);
eq('返回键先关键盘', w.__onBack(), true);
eq('键盘已关', doc.getElementById('keypad').classList.contains('on'), false);

const r = report();
console.log('errors:', errors.slice(0,6));
process.exit(r.fail?1:0);
